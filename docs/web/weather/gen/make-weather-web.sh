#!/bin/sh
# Regenerate docs/web/weather/lessons.js from src/weather/teach.awk.
#
# The lesson bodies are CODE, not data: lesson_body() prints them with
# lp/lpd/lph, so there is nothing to copy out. The generator RUNS the awk
# and captures what it actually prints, in COLOUR mode -- which is how the
# structure survives. lph wraps a heading in the accent colour, lpd wraps
# an aside in the dim colour, and inside a line cw() marks the words the
# author thought mattered. Converting those escapes rather than stripping
# them is what keeps the web lesson the same lesson.
#
# Run from the repository root:  sh docs/web/weather/gen/make-weather-web.sh
set -e
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
SRC="$ROOT/src/weather"
GEN="$ROOT/web/weather/gen"
OUT="$ROOT/web/weather/lessons.js"
TMP=${TMPDIR:-/tmp}/weather-lessons.$$
mkdir -p "$TMP"
trap 'rm -rf "$TMP"' EXIT

AWK=awk
for a in mawk gawk awk; do command -v "$a" >/dev/null 2>&1 && { AWK=$a; break; }; done

ENG="-f $ROOT/src/common/log.awk -f $ROOT/src/common/colour.awk \
     -f $SRC/wx.awk -f $SRC/score.awk -f $SRC/chart.awk -f $SRC/teach.awk \
     -f $SRC/screens.awk"


#  weather READS deck-log's log: same origin, same IndexedDB, which is
#  the one shared store the specification asks for. But a service worker
#  only serves what is inside its own scope, so ../deck-log/log.js would
#  be fetched from the network every time and the tool would not work
#  offline -- which is the entire point. So the two files are COPIED
#  here, and this checks they stay byte-identical rather than drifting
#  into two readers of one append-only format.
for f in log.js store.js; do
  cp "$ROOT/web/deck-log/$f" "$ROOT/web/weather/$f"
  if cmp -s "$ROOT/web/deck-log/$f" "$ROOT/web/weather/$f"; then
    echo "$f  copied from deck-log, byte-identical"
  else
    echo "make-weather-web: $f differs from deck-log's copy" >&2; exit 1
  fi
done

keys=$("$AWK" -v cmode=plain -v cmd=lessonlist -v LOG=/dev/null $ENG </dev/null)
[ -n "$keys" ] || { echo "make-weather-web: no lessons found" >&2; exit 1; }

#  the syllabus carries each lesson's one-line title
"$AWK" -v cmode=plain -v cmd=syllabus -v donelist= -v LOG=/dev/null $ENG </dev/null > "$TMP/syl"

{
  echo "// Generated by docs/web/weather/gen/make-weather-web.sh -- DO NOT EDIT."
  echo "// The lessons, captured from src/weather/teach.awk's own output so that"
  echo "// the words and the emphasis are the author's, not a transcription."
  echo "//"
  echo "// Every piece of physics here earns its place by changing what the app"
  echo "// says or what you would do. Otherwise it is a lecture with a barometer"
  echo "// attached."
  echo "'use strict';"
  echo "var LESSONS = ["
} > "$OUT"

for k in $keys; do
  title=$("$AWK" -v k="$k" '$1==k { $1=""; sub(/^[ \t]+/,""); print; exit }' "$TMP/syl")
  printf "  { key: '%s', title: '%s', body: [\n" "$k" "$title" >> "$OUT"
  "$AWK" -v cmode=day -v cmd=lesson -v key="$k" -v LOG=/dev/null $ENG </dev/null \
    | "$AWK" -f "$GEN/trimq.awk" \
    | "$AWK" -f "$GEN/dumplessons.awk" >> "$OUT"
  printf "  ], " >> "$OUT"
  #  cmd=lesson prints the body and then the question; cmd=lessonq prints
  #  the answer on its own. Both are taken from the tool rather than
  #  parsed back out of a page.
  "$AWK" -v cmode=plain -v cmd=lesson -v key="$k" -v LOG=/dev/null $ENG </dev/null \
    | "$AWK" -f "$GEN/dumpq.awk" >> "$OUT"
  "$AWK" -v cmode=plain -v cmd=lessonq -v key="$k" -v LOG=/dev/null $ENG </dev/null \
    | "$AWK" -f "$GEN/dumpa.awk" >> "$OUT"
done

{
  echo "];"
  echo "if (typeof module !== 'undefined') module.exports = { LESSONS: LESSONS };"
} >> "$OUT"

node -e '
var L = require(process.argv[1]).LESSONS;
console.log("lessons.js  " + L.length + " lessons, " +
  L.reduce(function (a, l) { return a + l.body.length; }, 0) + " lines");
L.forEach(function (l) { console.log("  " + l.key.padEnd(10) + l.title); });
' "$OUT"
