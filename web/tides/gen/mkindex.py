#!/usr/bin/env python3
"""Build web/tides/stations.idx from src/tides/stations.dat.

The index carries, for every station, enough to search it and to place it
on a chart, plus the BYTE OFFSET and LENGTH of its line in stations.dat.
That is what lets the browser pull one station's harmonic constants with a
Range request of a few hundred bytes instead of a megabyte: the index is
250 kB over the wire, the whole file is 1.1 MB.

Offsets are counted in BYTES, not characters.  Four station names are not
ASCII -- Saint Barthelemy and three in Curacao -- and a character offset
would land mid-line for every station after them.

Nothing is written unless every offset/length pair slices its own line
back out of the file, byte for byte.

Run from the repository root:  python3 web/tides/gen/mkindex.py
"""
import os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
SRC = os.path.join(ROOT, 'src', 'tides', 'stations.dat')
OUT = os.path.join(ROOT, 'web', 'tides', 'stations.idx')

if not os.path.isfile(SRC):
    sys.exit('mkindex: cannot find %s -- run this from the repository root' % SRC)

raw = open(SRC, 'rb').read()

rows, off = [], 0
for line in raw.split(b'\n'):
    n = len(line)
    if n and line[0:1] in (b'R', b'S'):
        f = line.split(b'|')
        if len(f) >= 8:
            rows.append((off, n, f))
    off += n + 1                       # the newline

def slice_ok(off, n, f):
    got = raw[off:off + n]
    return got.split(b'|') == f and b'\n' not in got

bad = [f[1] for off, n, f in rows if not slice_ok(off, n, f)]
if bad:
    sys.exit('mkindex: offset check failed for %d stations, first %r' % (len(bad), bad[0]))

out = []
for off, n, f in rows:
    out.append('%s|%s|%s|%s|%s|%.4f|%.4f|%d|%d' % (
        f[0].decode(), f[1].decode('utf-8'), f[2].decode('utf-8'),
        f[3].decode('utf-8'), f[4].decode('utf-8'),
        float(f[5]), float(f[6]), off, n))

body = ('# Bash Navigation Software tide station index\n'
        '# K|id|name|region|country|lat|lon|byte-offset|byte-length  into stations.dat\n'
        '# Generated by web/tides/gen/mkindex.py -- do not edit.\n'
        + '\n'.join(out) + '\n')

open(OUT, 'w', encoding='utf-8').write(body)
print('stations  %d  (R %d, S %d)' % (
    len(rows),
    sum(1 for _, _, f in rows if f[0] == b'R'),
    sum(1 for _, _, f in rows if f[0] == b'S')))
print('index     %d bytes -> %s' % (len(body.encode('utf-8')),
                                    os.path.relpath(OUT, ROOT)))
print('every offset/length slices its own line back out, byte for byte')
