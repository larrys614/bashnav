#!/usr/bin/env python3
"""
Generate the constituent, satellite and shallow-water tables for tides.awk.

The definitions come from UTide (Codiga), which carries Foreman's constituent
set - the same machinery t_tide uses.  Nothing here is hand-transcribed: the
tables are written straight out of that package, so a typo is not possible.
"""
# SA_FIX: Foreman and UTide give SA the Doodson numbers (0 0 1 0 0 -1),
# i.e. h - p'. The harmonic constants in this database come from NOAA and
# TICON, whose SA is referenced to h alone (speed 0.0410686 deg/hr, exactly
# the rate of h). p' is about 283 degrees, so keeping Foreman's convention
# throws SA's phase by nearly a full turn - which showed up as a vertical
# offset of +8 cm in August and -6 cm in February, checked against NOAA's
# own published predictions. SA is therefore emitted as (0 0 1 0 0 0).
import numpy as np, json, glob, sys
from utide._ut_constants import ut_constants as U

const, sat, shallow = U.const, U.sat, U.shallow
names = [str(x).strip() for x in const.name]
NAME_IDX = {n: i for i, n in enumerate(names)}

# names the station database uses that UTide spells differently
ALIAS = {'LAMBDA2':'LDA2', 'LAM2':'LDA2', 'SIGMA1':'SIG1', 'SGM':'SIG1',
         'RHO':'RHO1', 'THETA1':'THE1', 'EP2':'EPS2'}

def wanted_from_database(paths, floor=0.01):
    """Every constituent the station data actually uses, above `floor` metres."""
    want = set()
    for f in paths:
        d = json.load(open(f))
        if d.get('type') != 'reference':
            continue
        for c in (d.get('harmonic_constituents') or []):
            if abs(c['amplitude']) < floor:
                continue
            n = ALIAS.get(c['name'], c['name'])
            if n in NAME_IDX:
                want.add(n)
    return want

def closure(want):
    """Shallow-water constituents are defined from others; pull those in too."""
    nsh = np.ma.masked_invalid(const.nshallow)
    ish = np.ma.masked_invalid(const.ishallow)
    out = set(want)
    changed = True
    while changed:
        changed = False
        for n in list(out):
            i = NAME_IDX[n]
            if ish.mask[i]:
                continue
            i0 = int(ish[i]) - 1
            for k in range(int(nsh[i])):
                p = names[int(shallow.iname[i0 + k]) - 1]
                if p not in out:
                    out.add(p); changed = True
    return out

def main(dbglob, out):
    want = closure(wanted_from_database(sorted(glob.glob(dbglob))))
    want.discard('M7')          # utide wraps its phase before combining, which
                                # a 3.5 coefficient makes non-reproducible; it
                                # never reaches 1 cm anywhere in the database
    keep = sorted(want, key=lambda n: NAME_IDX[n])
    idx  = {n: i + 1 for i, n in enumerate(keep)}      # 1-based, for awk

    nsh = np.ma.masked_invalid(const.nshallow)
    ish = np.ma.masked_invalid(const.ishallow)
    nsat = np.ma.masked_invalid(const.nsat)
    isat = np.ma.masked_invalid(const.isat)

    L = []
    L.append("# generated by src/tides/gen/make_tables.py from UTide %s - do not edit"
             % str(U.ut_version))
    L.append("function tide_tables_init(   i,n,a){")
    L.append("  if(TT_READY) return")

    # constituents:  name | doodson x6 | semi | first satellite | n satellites
    #                     | first shallow term | n shallow terms
    rows = []
    for n in keep:
        i = NAME_IDX[n]
        d = const.doodson[i]
        dd = "" if not np.isfinite(d).all() else " ".join("%g" % x for x in d)
        sm = "" if not np.isfinite(const.semi[i]) else "%.10g" % const.semi[i]
        s0 = 0 if isat.mask[i] else int(isat[i])
        sn = 0 if nsat.mask[i] else int(nsat[i])
        h0 = 0 if ish.mask[i] else int(ish[i])
        hn = 0 if nsh.mask[i] else int(nsh[i])
        rows.append("%s|%s|%s|%d|%d|%d|%d" % (n, dd, sm, s0, sn, h0, hn))
    emit(L, "TT_CONST", rows)

    # satellites: deldood x3 | phcorr | amprat | ilatfac
    rows = ["%g %g %g|%.10g|%.10g|%d" %
            (sat.deldood[i][0], sat.deldood[i][1], sat.deldood[i][2],
             sat.phcorr[i], sat.amprat[i], int(sat.ilatfac[i]))
            for i in range(len(sat.iconst))]
    emit(L, "TT_SAT", rows)

    # shallow terms: index of the parent constituent (in our numbering) | coef
    rows = []
    for i in range(len(shallow.iname)):
        p = names[int(shallow.iname[i]) - 1]
        rows.append("%d|%.10g" % (idx.get(p, 0), shallow.coef[i]))
    emit(L, "TT_SHAL", rows)

    L.append('  TT_N=split(TT_CONST,a,";")')
    L.append('  for(i=1;i<=TT_N;i++){ n=split(a[i],CF,"|")')
    L.append('    CNAME[i]=CF[1]; CIDX[CF[1]]=i')
    L.append('    split(CF[2],DD_," "); CD1[i]=DD_[1]+0; CD2[i]=DD_[2]+0; CD3[i]=DD_[3]+0')
    L.append('    CD4[i]=DD_[4]+0; CD5[i]=DD_[5]+0; CD6[i]=DD_[6]+0; CDOK[i]=(CF[2]!="")')
    L.append('    CSEMI[i]=CF[3]+0; CS0[i]=CF[4]+0; CSN[i]=CF[5]+0; CH0[i]=CF[6]+0; CHN[i]=CF[7]+0 }')
    L.append('  n=split(TT_SAT,a,";")')
    L.append('  for(i=1;i<=n;i++){ split(a[i],CF,"|"); split(CF[1],DD_," ")')
    L.append('    SD1[i]=DD_[1]+0; SD2[i]=DD_[2]+0; SD3[i]=DD_[3]+0')
    L.append('    SPH[i]=CF[2]+0; SAMP[i]=CF[3]+0; SLAT[i]=CF[4]+0 }')
    L.append('  n=split(TT_SHAL,a,";")')
    L.append('  for(i=1;i<=n;i++){ split(a[i],CF,"|"); HIN[i]=CF[1]+0; HCO[i]=CF[2]+0 }')
    L.append('  TT_READY=1')
    L.append("}")

    open(out, "w").write("\n".join(L) + "\n")
    print("constituents kept: %d" % len(keep))
    print("satellites: %d   shallow terms: %d" % (len(sat.iconst), len(shallow.iname)))
    print("wrote %s (%d bytes)" % (out, len("\n".join(L))))
    json.dump({n: idx[n] for n in keep}, open(out + ".index.json", "w"))

def emit(L, var, rows):
    """Write a long ;-separated string as continued awk source."""
    line, chunks = "", []
    for r in rows:
        if len(line) + len(r) > 150:
            chunks.append(line.rstrip(";")); line = ""
        line += r + ";"
    chunks.append(line.rstrip(";"))
    L.append('  %s= \\' % var)
    for i, c in enumerate(chunks):
        cont = ' \\' if i < len(chunks) - 1 else ''
        L.append('  "%s%s"%s' % (c, ";" if i < len(chunks) - 1 else "", cont))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/tdb/data/*/*.json",
         sys.argv[2] if len(sys.argv) > 2 else "/home/claude/bashnav/src/tides/tables.awk")
